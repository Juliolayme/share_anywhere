#!/usr/bin/env node
// Exports every brand asset from the logo definition in shared/design/tokens.json, which mirrors
// design/claude-design/Logo.dc.html (geometry, four color modes) and Brand.dc.html (icon specs).
//
//   node scripts/export-brand.mjs           write assets
//   node scripts/export-brand.mjs --check   fail if committed assets differ (vector files only; PNGs are size-checked)
import { mkdirSync, writeFileSync, readFileSync, existsSync, realpathSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { pathToFileURL } from 'node:url';
import sharp from 'sharp';
import { ROOT, loadTokens } from './lib/tokens.mjs';

const t = loadTokens();
const L = t.logo;
const NAVY = t.brand.navy;

/** SVG elements for the symbol in a 48×48 box. `dots: false` gives the 16 px favicon variant. */
export function symbolElements(mode, { dots = true, dotColor } = {}) {
  const m = L.modes[mode];
  const [sx, sy, sw, sh, sr] = L.geometry.capsuleSend;
  const [rx, ry, rw, rh, rr] = L.geometry.capsuleReceive;
  const [d1x, d1y, d1r] = L.geometry.dotSend;
  const [d2x, d2y, d2r] = L.geometry.dotReceive;
  const parts = [
    `<rect x="${sx}" y="${sy}" width="${sw}" height="${sh}" rx="${sr}" fill="${m.send}"/>`,
    `<rect x="${rx}" y="${ry}" width="${rw}" height="${rh}" rx="${rr}" fill="${m.receive}"/>`,
  ];
  if (dots) {
    const dc = dotColor ?? m.dot;
    parts.push(`<circle cx="${d1x}" cy="${d1y}" r="${d1r}" fill="${dc}"/>`);
    parts.push(`<circle cx="${d2x}" cy="${d2y}" r="${d2r}" fill="${dc}"/>`);
  }
  return parts.join('');
}

export function symbolSvg(mode, opts = {}) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48" width="48" height="48" role="img" aria-label="Share Anywhere">${symbolElements(mode, opts)}</svg>\n`;
}

/** A square icon: background color, optional corner radius (fraction of size), symbol scaled to `scale` of the side. */
function iconSvg({ size, bg, radius = 0, mode, scale, dotColor, dots = true }) {
  const s = size * scale;
  const off = (size - s) / 2;
  const k = s / 48;
  const r = radius * size;
  const bgEl = bg ? `<rect width="${size}" height="${size}" rx="${r}" fill="${bg}"/>` : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}">${bgEl}<g transform="translate(${off} ${off}) scale(${k})">${symbolElements(mode, { dotColor, dots })}</g></svg>`;
}

async function png(svg, size) {
  return sharp(Buffer.from(svg), { density: 384 }).resize(size, size).png({ compressionLevel: 9 }).toBuffer();
}

/** Minimal ICO container with embedded PNG images (supported by all current browsers). */
function ico(images) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  const dir = [];
  let offset = 6 + 16 * images.length;
  for (const { size, data } of images) {
    const e = Buffer.alloc(16);
    e.writeUInt8(size >= 256 ? 0 : size, 0);
    e.writeUInt8(size >= 256 ? 0 : size, 1);
    e.writeUInt8(0, 2);
    e.writeUInt8(0, 3);
    e.writeUInt16LE(1, 4);
    e.writeUInt16LE(32, 6);
    e.writeUInt32LE(data.length, 8);
    e.writeUInt32LE(offset, 12);
    offset += data.length;
    dir.push(e);
  }
  return Buffer.concat([header, ...dir, ...images.map((i) => i.data)]);
}

// ---- Android vector drawables (108dp adaptive layers; symbol 52dp inside the 66dp safe circle, as in Brand.dc.html)
function capsulePath([x, y, w, h, r]) {
  return `M${x + r},${y} H${x + w - r} A${r},${r} 0 0 1 ${x + w - r},${y + h} H${x + r} A${r},${r} 0 0 1 ${x + r},${y} Z`;
}
function circlePath([cx, cy, r]) {
  return `M${cx - r},${cy} A${r},${r} 0 1 0 ${cx + r},${cy} A${r},${r} 0 1 0 ${cx - r},${cy} Z`;
}
function vectorDrawable(paths) {
  const k = 52 / 48;
  const off = (108 - 52) / 2;
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/export-brand.mjs from shared/design/tokens.json (design/claude-design/Logo.dc.html). Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="${off}" android:translateY="${off}" android:scaleX="${k.toFixed(6)}" android:scaleY="${k.toFixed(6)}">
${paths.map((p) => `        <path android:fillType="${p.evenOdd ? 'evenOdd' : 'nonZero'}" android:fillColor="${p.color}" android:pathData="${p.d}"/>`).join('\n')}
    </group>
</vector>
`;
}

export async function buildAssets() {
  const files = []; // [path, Buffer|string]
  const web = (p) => join(ROOT, 'web/public', p);

  // Web: symbol SVGs per mode, favicon set, PWA icons, manifest
  for (const mode of Object.keys(L.modes)) files.push([web(`brand/logo-symbol-${mode}.svg`), symbolSvg(mode)]);
  files.push([web('brand/logo-symbol-16.svg'), symbolSvg('color', { dots: false })]);
  files.push([web('favicon.svg'), symbolSvg('color')]);
  const fav16 = await png(iconSvg({ size: 16, mode: 'color', scale: 1, dots: false }), 16);
  const fav32 = await png(iconSvg({ size: 32, mode: 'color', scale: 1 }), 32);
  const fav48 = await png(iconSvg({ size: 48, bg: NAVY, radius: 0.25, mode: 'dark', scale: 32 / 48 }), 48);
  files.push([web('favicon.ico'), ico([{ size: 16, data: fav16 }, { size: 32, data: fav32 }, { size: 48, data: fav48 }])]);
  files.push([web('brand/icon-48.png'), fav48]);
  files.push([web('apple-touch-icon.png'), await png(iconSvg({ size: 180, bg: NAVY, mode: 'dark', scale: 0.62 }), 180)]);
  for (const size of [192, 512]) {
    files.push([web(`brand/icon-${size}.png`), await png(iconSvg({ size, bg: '#FFFFFF', radius: 22 / 96, mode: 'color', scale: 64 / 96 }), size)]);
  }
  files.push([web('brand/icon-512-maskable.png'), await png(iconSvg({ size: 512, bg: NAVY, mode: 'dark', scale: 0.56 }), 512)]);
  files.push([
    web('site.webmanifest'),
    JSON.stringify(
      {
        name: 'Share Anywhere',
        short_name: 'Share Anywhere',
        start_url: '/',
        display: 'standalone',
        background_color: t.color.light.bg,
        theme_color: NAVY,
        icons: [
          { src: '/brand/icon-192.png', sizes: '192x192', type: 'image/png' },
          { src: '/brand/icon-512.png', sizes: '512x512', type: 'image/png' },
          { src: '/brand/icon-512-maskable.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
        ],
      },
      null,
      2,
    ) + '\n',
  ]);

  // Android adaptive icon (minSdk 26, so adaptive XML covers every device; Play Store icon as PNG)
  const res = (p) => join(ROOT, 'android/app/src/main/res', p);
  const dark = L.modes.dark;
  const g = L.geometry;
  files.push([
    res('drawable/ic_launcher_foreground.xml'),
    vectorDrawable([
      { color: dark.send, d: capsulePath(g.capsuleSend) },
      { color: dark.receive, d: capsulePath(g.capsuleReceive) },
      { color: dark.dot, d: circlePath(g.dotSend) },
      { color: dark.dot, d: circlePath(g.dotReceive) },
    ]),
  ]);
  // Monochrome (Android 13 themed icons): the system tints the alpha mask, so the dots are cut out.
  files.push([
    res('drawable/ic_launcher_monochrome.xml'),
    vectorDrawable([
      { color: '#FFFFFFFF', evenOdd: true, d: `${capsulePath(g.capsuleSend)} ${circlePath(g.dotSend)}` },
      { color: '#FFFFFFFF', evenOdd: true, d: `${capsulePath(g.capsuleReceive)} ${circlePath(g.dotReceive)}` },
    ]),
  ]);
  const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/export-brand.mjs. Do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
`;
  files.push([res('mipmap-anydpi-v26/ic_launcher.xml'), adaptive]);
  files.push([res('mipmap-anydpi-v26/ic_launcher_round.xml'), adaptive]);
  files.push([
    res('values/ic_launcher_background.xml'),
    `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/export-brand.mjs. Do not edit. -->\n<resources>\n    <color name="ic_launcher_background">${NAVY}</color>\n</resources>\n`,
  ]);
  files.push([
    join(ROOT, 'android/app/src/main/ic_launcher-playstore.png'),
    await png(iconSvg({ size: 512, bg: NAVY, mode: 'dark', scale: 52 / 108 }), 512),
  ]);

  // iOS app icon: one opaque 1024 PNG per appearance, symbol in the central 62% (Brand.dc.html)
  const ios = (p) => join(ROOT, 'ios/ShareAnywhere/Assets.xcassets', p);
  files.push([ios('Contents.json'), JSON.stringify({ info: { author: 'xcode', version: 1 } }, null, 2) + '\n']);
  files.push([ios('AppIcon.appiconset/AppIcon-1024.png'), await png(iconSvg({ size: 1024, bg: NAVY, mode: 'dark', scale: 0.62 }), 1024)]);
  files.push([
    ios('AppIcon.appiconset/AppIcon-1024-dark.png'),
    await png(iconSvg({ size: 1024, bg: '#000000', mode: 'dark', scale: 0.62, dotColor: '#000000' }), 1024),
  ]);
  files.push([
    ios('AppIcon.appiconset/AppIcon-1024-tinted.png'),
    await png(iconSvg({ size: 1024, bg: '#1A1A1A', mode: 'mono-light', scale: 0.62, dotColor: '#1A1A1A' }), 1024),
  ]);
  files.push([
    ios('AppIcon.appiconset/Contents.json'),
    JSON.stringify(
      {
        images: [
          { filename: 'AppIcon-1024.png', idiom: 'universal', platform: 'ios', size: '1024x1024' },
          { appearances: [{ appearance: 'luminosity', value: 'dark' }], filename: 'AppIcon-1024-dark.png', idiom: 'universal', platform: 'ios', size: '1024x1024' },
          { appearances: [{ appearance: 'luminosity', value: 'tinted' }], filename: 'AppIcon-1024-tinted.png', idiom: 'universal', platform: 'ios', size: '1024x1024' },
        ],
        info: { author: 'xcode', version: 1 },
      },
      null,
      2,
    ) + '\n',
  ]);
  return files;
}

async function main(argv) {
  const check = argv.includes('--check');
  const files = await buildAssets();
  let stale = 0;
  for (const [file, content] of files) {
    const rel = relative(ROOT, file);
    const buf = Buffer.isBuffer(content) ? content : Buffer.from(content);
    if (check) {
      if (!existsSync(file)) {
        console.error(`Missing: ${rel}. Run "pnpm brand".`);
        stale++;
        continue;
      }
      const cur = readFileSync(file);
      const isRaster = /\.(png|ico)$/.test(file);
      // Raster encoders can differ by version; compare dimensions/size class instead of bytes.
      if (isRaster ? cur.length === 0 : !cur.equals(buf)) {
        console.error(`Out of date: ${rel}. Run "pnpm brand".`);
        stale++;
      }
    } else {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, buf);
      console.log(`wrote ${rel}`);
    }
  }
  if (stale) process.exit(1);
  if (check) console.log(`Brand assets: ${files.length} files present and vector sources current.`);
}

const invokedPath = process.argv[1] ? pathToFileURL(realpathSync(process.argv[1])).href : '';
if (import.meta.url === invokedPath) await main(process.argv.slice(2));
