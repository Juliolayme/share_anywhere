// Writes shared/protocol/schemas/cloud-vectors.json: Cloud Distribution part encryption and key wrap with fixed
// keys and nonces (docs/TRANSFER_PROTOCOL.md §9). Web, Android and iOS tests reproduce them byte for byte.
// Run: node scripts/gen-cloud-vectors.mjs
import {
  createCipheriv,
  createHash,
  createPrivateKey,
  createPublicKey,
  diffieHellman,
  hkdfSync,
} from "node:crypto";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const b64u = (b) => Buffer.from(b).toString("base64url");
const hex = (b) => Buffer.from(b).toString("hex");
const bytes = (n, seed) =>
  Buffer.from(Array.from({ length: n }, (_, i) => (i * 31 + seed) & 0xff));

function gcm(key, nonce, plain, aad) {
  const c = createCipheriv("aes-256-gcm", key, nonce);
  c.setAAD(Buffer.from(aad, "utf8"));
  return Buffer.concat([c.update(plain), c.final(), c.getAuthTag()]);
}

function x25519(seed) {
  const priv = createPrivateKey({
    key: Buffer.concat([
      Buffer.from("302e020100300506032b656e04220420", "hex"),
      seed,
    ]),
    format: "der",
    type: "pkcs8",
  });
  const pub = createPublicKey(priv)
    .export({ format: "der", type: "spki" })
    .subarray(-32);
  return { priv, pub };
}

const objectId = "0b5d6f1e-3a4c-4d2e-9f80-1a2b3c4d5e6f";
const fileId = "7c8d9e0f-1a2b-4c3d-8e4f-5a6b7c8d9e0f";
const sessionId = "11111111-2222-4333-8444-555555555555";
const receiverPid = "66666666-7777-4888-9999-aaaaaaaaaaaa";
const partSize = 16;
const file = bytes(40, 5); // three parts: 16, 16, 8
const key = bytes(32, 101);
const partCount = Math.ceil(file.length / partSize);
const parts = [];
for (let n = 0; n < partCount; n++) {
  const plain = file.subarray(
    n * partSize,
    Math.min(file.length, (n + 1) * partSize),
  );
  const nonce = bytes(12, 200 + n);
  const aad = `sa-cloud-v1|${objectId}|${n}|${partCount}`;
  parts.push({
    n,
    aad,
    nonce: hex(nonce),
    plaintext: hex(plain),
    stored: hex(Buffer.concat([nonce, gcm(key, nonce, plain, aad)])),
  });
}
const fileSha = createHash("sha256").update(file).digest();

const r = x25519(bytes(32, 7));
const s = x25519(bytes(32, 9));
const shared = diffieHellman({
  privateKey: s.priv,
  publicKey: createPublicKey({
    key: Buffer.concat([Buffer.from("302a300506032b656e032100", "hex"), r.pub]),
    format: "der",
    type: "spki",
  }),
});
const info = `sa-cloud-key-v1|${sessionId}|${receiverPid}`;
const wrapKey = Buffer.from(
  hkdfSync(
    "sha256",
    shared,
    Buffer.concat([s.pub, r.pub]),
    Buffer.from(info, "utf8"),
    32,
  ),
);
const wrapNonce = bytes(12, 60);
const wrapAad = `sa-cloud-wrap-v1|${objectId}|${fileId}`;
const wrapped = gcm(wrapKey, wrapNonce, Buffer.concat([key, fileSha]), wrapAad);

const out = {
  $comment:
    "Cloud Distribution vectors (docs/TRANSFER_PROTOCOL.md §9), generated by scripts/gen-cloud-vectors.mjs. Hex unless the field ends in _b64u (base64url without padding). Stored part = nonce || AES-256-GCM(key, nonce, plaintext, aad) with the 16-byte tag appended. Key wrap: W = HKDF-SHA256(X25519(sender, receiver.pub), salt = sender.pub || receiver.pub, info, 32); wrapped = AES-256-GCM(W, nonce, key || sha256(file), aad).",
  part: {
    object_id: objectId,
    part_size: partSize,
    part_count: partCount,
    file: hex(file),
    file_sha256: hex(fileSha),
    key: hex(key),
    parts,
  },
  wrap: {
    session_id: sessionId,
    receiver_participant_id: receiverPid,
    object_id: objectId,
    file_id: fileId,
    receiver_private: hex(bytes(32, 7)),
    receiver_public_b64u: b64u(r.pub),
    sender_private: hex(bytes(32, 9)),
    sender_public_b64u: b64u(s.pub),
    shared: hex(shared),
    info,
    wrap_key: hex(wrapKey),
    aad: wrapAad,
    nonce_b64u: b64u(wrapNonce),
    wrapped_b64u: b64u(wrapped),
  },
};
writeFileSync(
  path.join(root, "shared/protocol/schemas/cloud-vectors.json"),
  JSON.stringify(out, null, 2) + "\n",
);
console.log("wrote shared/protocol/schemas/cloud-vectors.json");
