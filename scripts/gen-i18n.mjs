#!/usr/bin/env node
// Generates EN/VI string catalogs from the Claude Design handoff (CLAUDE.md, UI source of truth).
//
// Sources, all in design/claude-design/:
//   i18n-strings.json  ui.en / ui.vi   named strings            -> "common"
//                      generated       EN text -> VI dictionary  -> "phrases" (slug keys)
//   Web App.dc.html     const T = {en, vi}                      -> "web"
//   Android App.dc.html const T = {en, vi}                      -> "android"
//   iOS App.dc.html     const T = {en, vi}                      -> "ios"
// The T tables are parsed as JSON5 data (never executed).
//
//   node scripts/gen-i18n.mjs           write shared/i18n/en.json and vi.json
//   node scripts/gen-i18n.mjs --check   fail if they are out of date or EN/VI keys differ
import { readFileSync, writeFileSync, mkdirSync, realpathSync } from 'node:fs';
import { join, relative } from 'node:path';
import { pathToFileURL } from 'node:url';
import JSON5 from 'json5';
import { ROOT } from './lib/tokens.mjs';

const DESIGN = join(ROOT, 'design/claude-design');
const OUT = join(ROOT, 'shared/i18n');
const HEADER = 'Generated by scripts/gen-i18n.mjs from design/claude-design. Do not edit; re-import the design and regenerate.';

/** Extracts the object literal assigned to `const <name> = {...}` using brace matching that respects strings. */
export function extractObjectLiteral(source, name) {
  const start = source.indexOf(`const ${name} = {`);
  if (start < 0) throw new Error(`const ${name} not found`);
  let i = source.indexOf('{', start);
  const begin = i;
  let depth = 0;
  let quote = null;
  for (; i < source.length; i++) {
    const c = source[i];
    if (quote) {
      if (c === '\\') i++;
      else if (c === quote) quote = null;
      continue;
    }
    if (c === "'" || c === '"' || c === '`') quote = c;
    else if (c === '{') depth++;
    else if (c === '}' && --depth === 0) return source.slice(begin, i + 1);
  }
  throw new Error(`Unterminated object literal for ${name}`);
}

export function slugify(text) {
  const s = text
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[\u0111\u0110]/g, 'd')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, 60);
  return s || 'phrase';
}

function sortKeys(obj) {
  if (Array.isArray(obj) || typeof obj !== 'object' || obj === null) return obj;
  return Object.fromEntries(Object.keys(obj).sort().map((k) => [k, sortKeys(obj[k])]));
}

export function flatten(obj, prefix = '') {
  const out = {};
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === 'object') Object.assign(out, flatten(v, key));
    else out[key] = v;
  }
  return out;
}

const placeholders = (s) => (String(s).match(/\{[a-zA-Z0-9_]+\}/g) ?? []).sort().join(',');

export function buildCatalogs() {
  const strings = JSON.parse(readFileSync(join(DESIGN, 'i18n-strings.json'), 'utf8'));
  const en = { common: strings.ui.en, phrases: {} };
  const vi = { common: strings.ui.vi, phrases: {} };

  const used = new Map();
  for (const [enText, viText] of Object.entries(strings.generated)) {
    let key = slugify(enText);
    if (used.has(key)) {
      let n = 2;
      while (used.has(`${key}_${n}`)) n++;
      key = `${key}_${n}`;
    }
    used.set(key, enText);
    en.phrases[key] = enText;
    vi.phrases[key] = viText;
  }

  for (const [ns, file] of [
    ['web', 'Web App.dc.html'],
    ['android', 'Android App.dc.html'],
    ['ios', 'iOS App.dc.html'],
  ]) {
    const table = JSON5.parse(extractObjectLiteral(readFileSync(join(DESIGN, file), 'utf8'), 'T'));
    en[ns] = table.en;
    vi[ns] = table.vi;
  }
  return { en: sortKeys(en), vi: sortKeys(vi) };
}

/** Problems that make a catalog unusable: missing keys, empty strings, mismatched placeholders. */
export function validateCatalogs({ en, vi }) {
  const problems = [];
  const fe = flatten(en);
  const fv = flatten(vi);
  for (const k of Object.keys(fe)) if (!(k in fv)) problems.push(`missing in vi: ${k}`);
  for (const k of Object.keys(fv)) if (!(k in fe)) problems.push(`missing in en: ${k}`);
  for (const [k, v] of Object.entries(fe)) {
    if (typeof v !== 'string' || v.trim() === '') problems.push(`empty en string: ${k}`);
    if (k in fv && placeholders(v) !== placeholders(fv[k])) problems.push(`placeholder mismatch: ${k}`);
  }
  for (const [k, v] of Object.entries(fv)) if (typeof v !== 'string' || v.trim() === '') problems.push(`empty vi string: ${k}`);
  return problems;
}

function render(locale, catalog) {
  return JSON.stringify({ $comment: HEADER, locale, ...catalog }, null, 2) + '\n';
}

function main(argv) {
  const check = argv.includes('--check');
  const catalogs = buildCatalogs();
  const problems = validateCatalogs(catalogs);
  if (problems.length) {
    console.error('i18n catalogs are invalid:\n  ' + problems.join('\n  '));
    process.exit(1);
  }
  let stale = 0;
  for (const locale of ['en', 'vi']) {
    const file = join(OUT, `${locale}.json`);
    const content = render(locale, catalogs[locale]);
    if (check) {
      let cur = '';
      try {
        cur = readFileSync(file, 'utf8');
      } catch {
        /* missing */
      }
      if (cur !== content) {
        console.error(`Out of date: ${relative(ROOT, file)}. Run "pnpm i18n".`);
        stale++;
      }
    } else {
      mkdirSync(OUT, { recursive: true });
      writeFileSync(file, content);
      console.log(`wrote ${relative(ROOT, file)} (${Object.keys(flatten(catalogs[locale])).length} strings)`);
    }
  }
  if (stale) process.exit(1);
  if (check) console.log(`i18n: EN/VI catalogs current, ${Object.keys(flatten(catalogs.en)).length} keys each, placeholders match.`);
}

const invokedPath = process.argv[1] ? pathToFileURL(realpathSync(process.argv[1])).href : '';
if (import.meta.url === invokedPath) main(process.argv.slice(2));
