#!/usr/bin/env node
// Generates EN/VI string catalogs from the Claude Design handoff (CLAUDE.md, UI source of truth).
//
// Sources, all in design/claude-design/ unless noted:
//   i18n-strings.json   ui.en / ui.vi   named strings              -> "common"
//                       generated       EN text -> VI dictionary   -> "phrases" (slug keys)
//   <App>.dc.html       every `const NAME = { en: {...}, vi: {...} }` table:
//                       T -> "<app>", any other NAME -> "<app>_<name>" (web, android, ios)
//   <App>.dc.html       `const TRP = [[/regex/, m => expr], ...]` VI pattern translations
//                       -> "<app>_patterns" as EN/VI templates with {1}, {2} placeholders
//                       (regex and expression are parsed as text, never executed)
//   <App>.dc.html       `L('en', 'vi')` inline pairs (connection log)  -> "<app>_log" (parsed as text)
//   Handoff Checklist.dc.html  `copy: [[key, en, vi], ...]`   -> "handoff"
//   shared/i18n/product.json   PRD strings the design lacks     -> "product" (hand-written)
// All tables are parsed as JSON5 data (never executed). A table that looks like {en, vi} but cannot be parsed fails the run.
//
// The Android app's slice (android, android_*, common, phrases, product, handoff) is also written as string resources:
//   android/app/src/main/res/values/strings.xml and values-vi/strings.xml ("ns.key" -> ns_key).
// The iOS app's slice (ios, ios_*, common, phrases, product, handoff) is written as one String Catalog:
//   ios/ShareAnywhere/Resources/Localizable.xcstrings (keys "ns.key").
//
//   node scripts/gen-i18n.mjs           write shared/i18n/en.json, vi.json and the Android string resources
//   node scripts/gen-i18n.mjs --check   fail if any of them is out of date or EN/VI keys differ
import { readFileSync, writeFileSync, mkdirSync, realpathSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { pathToFileURL } from 'node:url';
import JSON5 from 'json5';
import { ROOT } from './lib/tokens.mjs';

const DESIGN = join(ROOT, 'design/claude-design');
const OUT = join(ROOT, 'shared/i18n');
const HEADER = 'Generated by scripts/gen-i18n.mjs from design/claude-design. Do not edit; re-import the design and regenerate.';

/** Extracts the object literal assigned to `const <name> = {...}` using brace matching that respects strings. */
export function extractObjectLiteral(source, name) {
  const start = source.indexOf(`const ${name} = {`);
  if (start < 0) throw new Error(`const ${name} not found`);
  let i = source.indexOf('{', start);
  const begin = i;
  let depth = 0;
  let quote = null;
  for (; i < source.length; i++) {
    const c = source[i];
    if (quote) {
      if (c === '\\') i++;
      else if (c === quote) quote = null;
      continue;
    }
    if (c === "'" || c === '"' || c === '`') quote = c;
    else if (c === '{') depth++;
    else if (c === '}' && --depth === 0) return source.slice(begin, i + 1);
  }
  throw new Error(`Unterminated object literal for ${name}`);
}

export function slugify(text) {
  const s = text
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[\u0111\u0110]/g, 'd')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, 60);
  return s || 'phrase';
}

function sortKeys(obj) {
  if (Array.isArray(obj) || typeof obj !== 'object' || obj === null) return obj;
  return Object.fromEntries(Object.keys(obj).sort().map((k) => [k, sortKeys(obj[k])]));
}

export function flatten(obj, prefix = '') {
  const out = {};
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === 'object') Object.assign(out, flatten(v, key));
    else out[key] = v;
  }
  return out;
}

const placeholders = (s) => (String(s).match(/\{[a-zA-Z0-9_]+\}/g) ?? []).sort().join(',');

/** Every `const NAME = {...}` in a prototype whose value is an {en, vi} string table. */
export function extractLocaleTables(source) {
  const tables = {};
  for (const m of source.matchAll(/const ([A-Z][A-Z0-9_]*) = \{/g)) {
    const name = m[1];
    const literal = extractObjectLiteral(source.slice(m.index), name);
    const looksLocale = /^\{\s*["']?en["']?\s*:/.test(literal);
    if (!looksLocale) continue;
    let parsed;
    try {
      parsed = JSON5.parse(literal);
    } catch (e) {
      throw new Error(`Locale table ${name} could not be parsed: ${e.message}`);
    }
    if (!parsed.en || !parsed.vi) throw new Error(`Locale table ${name} lacks en or vi`);
    tables[name] = parsed;
  }
  return tables;
}

/**
 * Converts one TRP entry (a regex over an English string and a JS concatenation that builds the
 * Vietnamese string from capture groups) into an EN/VI template pair with {1}, {2} placeholders.
 * Supported regex syntax: literals, escapes, capture groups ( ... ), optional single characters (x?),
 * optional groups ((...)?) which are dropped, and alternation groups ((a|b)) which keep the last
 * alternative (the plural form). Anything else throws so the design cannot silently drift.
 */
export function patternToTemplates(regexSource, viExpr) {
  let src = regexSource;
  if (!src.startsWith('^') || !src.endsWith('$')) throw new Error(`Pattern not anchored: ${regexSource}`);
  src = src.slice(1, -1);
  let en = '';
  let group = 0;
  const placeholders = new Set();
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (c === '\\') {
      en += src[++i];
    } else if (c === '(') {
      // find the matching close paren (no nested groups in the design patterns)
      const close = src.indexOf(')', i);
      if (close < 0) throw new Error(`Unclosed group in ${regexSource}`);
      const inner = src.slice(i + 1, close);
      group++;
      const optional = src[close + 1] === '?';
      if (optional) {
        i = close + 1; // optional literal group: dropped
      } else if (/^[a-z ]+(\|[a-z ]+)+$/i.test(inner)) {
        en += inner.split('|').pop(); // alternation: keep the last (plural) form
        i = close;
      } else {
        en += `{${group}}`;
        placeholders.add(group);
        i = close;
      }
    } else if (src[i + 1] === '?' && /[a-z,]/i.test(c)) {
      if (c !== ',') en += c; // optional single character: keep letters (plural), drop commas
      i++;
    } else if ('[]+*.|{}'.includes(c)) {
      throw new Error(`Unsupported regex syntax "${c}" in ${regexSource}`);
    } else {
      en += c;
    }
  }
  let vi = '';
  for (const part of viExpr.split(/\s*\+\s*/)) {
    const g = /^m\[(\d+)\]$/.exec(part);
    const str = /^'((?:[^'\\]|\\.)*)'$/.exec(part);
    if (g) {
      const n = Number(g[1]);
      if (!placeholders.has(n)) throw new Error(`VI uses group ${n} that EN drops: ${regexSource}`);
      vi += `{${n}}`;
    } else if (str) {
      vi += str[1].replace(/\\(.)/g, '$1');
    } else {
      throw new Error(`Unsupported VI expression part "${part}" in ${viExpr}`);
    }
  }
  return { en, vi };
}

/** Every entry of `const TRP = [...]` in a prototype as {key: {en, vi}}. */
export function extractPatternTable(source) {
  const start = source.indexOf('const TRP = [');
  if (start < 0) return null;
  const line = source.slice(start + 'const TRP = ['.length, source.indexOf('\n', start));
  const entries = [...line.matchAll(/\[\/(.*?)\/, m => (.*?)\](?=, \[|\];?\s*$)/g)];
  if (!entries.length) throw new Error('TRP table found but no entries could be read');
  // Every "[/" that opens an entry must have been read, so a new entry shape cannot be skipped silently.
  const opened = (line.match(/\[\//g) ?? []).length;
  if (opened !== entries.length) throw new Error(`TRP has ${opened} entries but ${entries.length} were converted`);
  const en = {};
  const vi = {};
  for (const [, re, expr] of entries) {
    const t = patternToTemplates(re, expr);
    let key = slugify(t.en.replace(/\{\d+\}/g, 'x'));
    let n = 2;
    while (key in en) key = `${slugify(t.en.replace(/\{\d+\}/g, 'x'))}_${n++}`;
    en[key] = t.en;
    vi[key] = t.vi;
  }
  return { en, vi };
}

/** Inline `L('en', 'vi')` pairs (the prototypes' connection-log helper) as {key: {en, vi}}. */
export function extractInlinePairs(source) {
  const en = {};
  const vi = {};
  let matched = 0;
  for (const m of source.matchAll(/\bL\('((?:[^'\\]|\\.)*)',\s*'((?:[^'\\]|\\.)*)'\)/g)) {
    matched++;
    const e = m[1].replace(/\\(.)/g, '$1');
    const v = m[2].replace(/\\(.)/g, '$1');
    const key = slugify(e);
    if (key in en && (en[key] !== e || vi[key] !== v)) {
      throw new Error(`inline L() pairs collide on key "${key}": "${en[key]}" vs "${e}"`);
    }
    en[key] = e;
    vi[key] = v;
  }
  // Every L( call must be a single-quoted literal pair; anything else would be skipped silently.
  const calls = (source.match(/\bL\(/g) || []).length;
  if (calls !== matched) {
    throw new Error(`found ${calls} L( calls but extracted ${matched}; update extractInlinePairs for the new form`);
  }
  return Object.keys(en).length ? { en, vi } : null;
}

/** The Handoff Checklist's key microcopy list: [[key, en, vi], ...]. */
export function extractHandoffCopy(source) {
  const start = source.indexOf('copy: [');
  if (start < 0) throw new Error('Handoff Checklist copy list not found');
  let i = source.indexOf('[', start);
  const begin = i;
  let depth = 0;
  let quote = null;
  for (; i < source.length; i++) {
    const c = source[i];
    if (quote) {
      if (c === '\\') i++;
      else if (c === quote) quote = null;
      continue;
    }
    if (c === "'" || c === '"') quote = c;
    else if (c === '[') depth++;
    else if (c === ']' && --depth === 0) break;
  }
  const rows = JSON5.parse(source.slice(begin, i + 1));
  return {
    en: Object.fromEntries(rows.map(([k, en]) => [k, en])),
    vi: Object.fromEntries(rows.map(([k, , vi]) => [k, vi])),
  };
}

export function buildCatalogs() {
  const strings = JSON.parse(readFileSync(join(DESIGN, 'i18n-strings.json'), 'utf8'));
  const en = { common: strings.ui.en, phrases: {} };
  const vi = { common: strings.ui.vi, phrases: {} };

  const used = new Map();
  for (const [enText, viText] of Object.entries(strings.generated)) {
    let key = slugify(enText);
    if (used.has(key)) {
      let n = 2;
      while (used.has(`${key}_${n}`)) n++;
      key = `${key}_${n}`;
    }
    used.set(key, enText);
    en.phrases[key] = enText;
    vi.phrases[key] = viText;
  }

  for (const [app, file] of [
    ['web', 'Web App.dc.html'],
    ['android', 'Android App.dc.html'],
    ['ios', 'iOS App.dc.html'],
  ]) {
    const tables = extractLocaleTables(readFileSync(join(DESIGN, file), 'utf8'));
    if (!tables.T) throw new Error(`${file}: string table T not found`);
    for (const [name, table] of Object.entries(tables)) {
      const ns = name === 'T' ? app : `${app}_${name.toLowerCase()}`;
      en[ns] = table.en;
      vi[ns] = table.vi;
    }
    const pairs = extractInlinePairs(readFileSync(join(DESIGN, file), 'utf8'));
    if (pairs) {
      en[`${app}_log`] = pairs.en;
      vi[`${app}_log`] = pairs.vi;
    }
    const patterns = extractPatternTable(readFileSync(join(DESIGN, file), 'utf8'));
    if (patterns) {
      en[`${app}_patterns`] = patterns.en;
      vi[`${app}_patterns`] = patterns.vi;
    }
  }

  const handoff = extractHandoffCopy(readFileSync(join(DESIGN, 'Handoff Checklist.dc.html'), 'utf8'));
  en.handoff = handoff.en;
  vi.handoff = handoff.vi;

  const product = JSON.parse(readFileSync(join(OUT, 'product.json'), 'utf8'));
  en.product = product.en;
  vi.product = product.vi;
  return { en: sortKeys(en), vi: sortKeys(vi) };
}

/** Problems that make a catalog unusable: missing keys, empty strings, mismatched placeholders. */
export function validateCatalogs({ en, vi }) {
  const problems = [];
  const fe = flatten(en);
  const fv = flatten(vi);
  for (const k of Object.keys(fe)) if (!(k in fv)) problems.push(`missing in vi: ${k}`);
  for (const k of Object.keys(fv)) if (!(k in fe)) problems.push(`missing in en: ${k}`);
  for (const [k, v] of Object.entries(fe)) {
    if (typeof v !== 'string' || v.trim() === '') problems.push(`empty en string: ${k}`);
    if (k in fv && placeholders(v) !== placeholders(fv[k])) problems.push(`placeholder mismatch: ${k}`);
  }
  for (const [k, v] of Object.entries(fv)) if (typeof v !== 'string' || v.trim() === '') problems.push(`empty vi string: ${k}`);
  return problems;
}

function render(locale, catalog) {
  return JSON.stringify({ $comment: HEADER, locale, ...catalog }, null, 2) + '\n';
}


const ANDROID_RES = join(ROOT, 'android/app/src/main/res');

/** Catalog namespaces the Android app ships: its own design tables plus the shared ones. */
export function isAndroidNamespace(ns) {
  return ns === 'android' || ns.startsWith('android_') || ['common', 'phrases', 'product', 'handoff'].includes(ns);
}

/** "android_yy.cb_clear" -> "android_yy_cb_clear" (aapt2 resource names: letters, digits, underscores). */
export function androidResourceName(flatKey) {
  const name = flatKey.replace(/[^A-Za-z0-9_]/g, '_');
  if (!/^[A-Za-z]/.test(name)) throw new Error(`Android resource name must start with a letter: ${flatKey}`);
  return name;
}

/** Escapes a catalog string for an Android <string> element (aapt2 rules), keeping {placeholders} as text. */
export function escapeAndroidString(text) {
  let s = String(text)
    .replace(/\\/g, '\\\\')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"')
    .replace(/\n/g, '\\n')
    .replace(/\t/g, '\\t');
  if (/^[@?]/.test(s)) s = `\\${s}`;
  // aapt2 trims and collapses whitespace: keep leading, trailing, and repeated spaces as escapes.
  s = s.replace(/^ +| +$/g, (m) => '\\u0020'.repeat(m.length)).replace(/ {2,}/g, (m) => ` ${'\\u0020'.repeat(m.length - 1)}`);
  return s;
}

/** The Android slice of one locale's catalog as {resourceName: text}; fails on a name collision. */
export function androidStrings(catalog) {
  const out = {};
  const from = {};
  for (const [ns, table] of Object.entries(catalog)) {
    if (!isAndroidNamespace(ns) || typeof table !== 'object') continue;
    for (const [key, text] of Object.entries(flatten(table, ns))) {
      const name = androidResourceName(key);
      if (name in out) throw new Error(`Android string names collide: ${from[name]} and ${key} -> ${name}`);
      out[name] = text;
      from[name] = key;
    }
  }
  return out;
}

export function renderAndroidStrings(catalog) {
  const lines = ['<?xml version="1.0" encoding="utf-8"?>', `<!-- ${HEADER} Source: scripts/gen-i18n.mjs (Android slice). -->`, '<resources>'];
  for (const [name, text] of Object.entries(androidStrings(catalog)).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
    const formatted = String(text).includes('%') ? ' formatted="false"' : '';
    lines.push(`    <string name="${name}"${formatted}>${escapeAndroidString(text)}</string>`);
  }
  lines.push('</resources>', '');
  return lines.join('\n');
}

// ---------------------------------------------------------------------------------------------------------
// iOS: the iOS slice (ios, ios_*, common, phrases, product, handoff) as one String Catalog,
// ios/ShareAnywhere/Resources/Localizable.xcstrings, keys "ns.key" as in the catalogs. {placeholders} stay text; the
// app fills them (ios/ShareAnywhere/Design/L10n.swift), as Android does, so no value is a printf format.

const IOS_STRINGS = join(ROOT, 'ios/ShareAnywhere/Resources/Localizable.xcstrings');

export function isIosNamespace(ns) {
  return ns === 'ios' || ns.startsWith('ios_') || ['common', 'phrases', 'product', 'handoff'].includes(ns);
}

/** The iOS slice of one locale's catalog as {flatKey: text}. */
export function iosStrings(catalog) {
  const out = {};
  for (const [ns, table] of Object.entries(catalog)) {
    if (!isIosNamespace(ns) || typeof table !== 'object') continue;
    Object.assign(out, flatten(table, ns));
  }
  return out;
}

export function renderXcstrings(catalogs) {
  const en = iosStrings(catalogs.en);
  const vi = iosStrings(catalogs.vi);
  const strings = {};
  for (const key of Object.keys(en).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))) {
    const unit = (value) => ({ stringUnit: { state: 'translated', value } });
    strings[key] = { comment: HEADER, extractionState: 'manual', localizations: { en: unit(en[key]), vi: unit(vi[key] ?? en[key]) } };
  }
  return JSON.stringify({ sourceLanguage: 'en', strings, version: '1.0' }, null, 2) + '\n';
}

/** Every generated file with its expected content. */
export function generatedFiles(catalogs) {
  return [
    ...['en', 'vi'].map((locale) => [join(OUT, `${locale}.json`), render(locale, catalogs[locale])]),
    [join(ANDROID_RES, 'values/strings.xml'), renderAndroidStrings(catalogs.en)],
    [join(ANDROID_RES, 'values-vi/strings.xml'), renderAndroidStrings(catalogs.vi)],
    [IOS_STRINGS, renderXcstrings(catalogs)],
  ];
}

function main(argv) {
  const check = argv.includes('--check');
  const catalogs = buildCatalogs();
  const problems = validateCatalogs(catalogs);
  if (problems.length) {
    console.error('i18n catalogs are invalid:\n  ' + problems.join('\n  '));
    process.exit(1);
  }
  let stale = 0;
  for (const [file, content] of generatedFiles(catalogs)) {
    if (check) {
      let cur = '';
      try {
        cur = readFileSync(file, 'utf8');
      } catch {
        /* missing */
      }
      if (cur !== content) {
        console.error(`Out of date: ${relative(ROOT, file)}. Run "pnpm i18n".`);
        stale++;
      }
    } else {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, content);
      console.log(`wrote ${relative(ROOT, file)}`);
    }
  }
  if (stale) process.exit(1);
  if (check) console.log(`i18n: EN/VI catalogs current, ${Object.keys(flatten(catalogs.en)).length} keys each, placeholders match; Android string resources and the iOS String Catalog current.`);
}

const invokedPath = process.argv[1] ? pathToFileURL(realpathSync(process.argv[1])).href : '';
if (import.meta.url === invokedPath) main(process.argv.slice(2));
