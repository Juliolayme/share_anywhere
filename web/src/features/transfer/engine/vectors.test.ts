// @vitest-environment node
/**
 * Shared transfer test vectors (shared/protocol/schemas/transfer-vectors.json). Android and iOS engines
 * must reproduce every hex string here. Regenerate with UPDATE_VECTORS=1 only for a protocol version bump.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { Bitmap } from './bitmap';
import {
  DIGEST_BYTES,
  FLAG_FIRST,
  FLAG_LAST,
  FrameType,
  blockCount,
  blockLength,
  dataPerFrame,
  encodeFrame,
  jsonFrame,
} from './frame';
import { hex } from './hash';

const PATH = new URL('../../../../../shared/protocol/schemas/transfer-vectors.json', import.meta.url).pathname;
const pattern = (n: number, from = 0) => Uint8Array.from({ length: n }, (_, i) => ((from + i) * 31 + 7) & 0xff);
const sha = (b: Uint8Array) => createHash('sha256').update(b).digest('hex');
const h = (b: ArrayBuffer) => hex(new Uint8Array(b));

function build() {
  const blockSize = 65536;
  const size = 200_000;
  const file = pattern(size);
  const blocks = Array.from({ length: blockCount(size, blockSize) }, (_, i) =>
    sha(file.subarray(i * blockSize, i * blockSize + blockLength(size, i, blockSize))),
  );
  const firstBlock = file.subarray(0, blockSize);
  const digest = Buffer.from(sha(firstBlock), 'hex');
  const per = dataPerFrame(65536);
  const firstPayload = new Uint8Array(DIGEST_BYTES + 16);
  firstPayload.set(digest, 0);
  firstPayload.set(firstBlock.subarray(0, 16), DIGEST_BYTES);
  const bm = new Bitmap(10);
  [0, 3, 9].forEach((i) => bm.set(i));
  const frames = [
    {
      name: 'HELLO receiver',
      hex: h(
        jsonFrame(FrameType.HELLO, {
          v: 1,
          role: 'receiver',
          session_id: 's1',
          participant_id: 'p1',
          capability: 'c1',
        }),
      ),
    },
    { name: 'HELLO sender', hex: h(jsonFrame(FrameType.HELLO, { v: 1, role: 'sender', session_id: 's1' })) },
    {
      name: 'FILE_META',
      hex: h(
        jsonFrame(FrameType.FILE_META, {
          files: [
            {
              file: 0,
              file_id: 'f1',
              transfer_id: 't1',
              name: 'a.bin',
              size,
              mime: 'application/octet-stream',
              block_size: blockSize,
              block_count: 4,
            },
          ],
        }),
      ),
    },
    {
      name: 'BITMAP file 0, blocks {0,3,9} of 10',
      hex: h(encodeFrame({ type: FrameType.BITMAP, file: 0, payload: bm.bytes })),
    },
    {
      name: 'BLOCK first frame (digest + first 16 bytes), file 0 block 0',
      hex: h(
        encodeFrame({ type: FrameType.BLOCK, flags: FLAG_FIRST, file: 0, block: 0, offset: 0, payload: firstPayload }),
      ),
    },
    {
      name: 'BLOCK last frame, file 0 block 3 at offset 4096, 8 bytes',
      hex: h(
        encodeFrame({
          type: FrameType.BLOCK,
          flags: FLAG_LAST,
          file: 0,
          block: 3,
          offset: 4096,
          payload: pattern(8, 3 * blockSize + 4096),
        }),
      ),
    },
    { name: 'ACK file 0 block 2', hex: h(encodeFrame({ type: FrameType.ACK, file: 0, block: 2 })) },
    { name: 'NACK file 0 block 2 checksum', hex: h(jsonFrame(FrameType.NACK, { reason: 'checksum' }, 0, 2)) },
    { name: 'PAUSE', hex: h(encodeFrame({ type: FrameType.PAUSE })) },
    { name: 'RESUME', hex: h(encodeFrame({ type: FrameType.RESUME })) },
    { name: 'DONE file 0 from the sender', hex: h(jsonFrame(FrameType.DONE, { sha256: sha(file) }, 0)) },
    { name: 'ERROR cancelled', hex: h(jsonFrame(FrameType.ERROR, { code: 'cancelled', fatal: true })) },
  ];
  return {
    $comment:
      'Generated by web/src/features/transfer/engine/vectors.test.ts (UPDATE_VECTORS=1). Protocol: docs/TRANSFER_PROTOCOL.md. JSON payloads are compact JSON.stringify output with keys in the order shown.',
    protocol_version: 1,
    data_pattern: 'byte[i] = (i * 31 + 7) mod 256, where i is the offset in the file',
    frames,
    bitmaps: [
      { blocks: 10, set: [0, 3, 9], hex: hex(bm.bytes), missing: bm.missing() },
      { blocks: 8, set: [0, 1, 2, 3, 4, 5, 6, 7], hex: 'ff', missing: [] },
      { blocks: 0, set: [], hex: '', missing: [] },
      { blocks: 5120, set: [5119], hex: '00'.repeat(639) + '80', missing_count: 5119 },
    ],
    file: { size, block_size: blockSize, block_count: blocks.length, block_sha256: blocks, sha256: sha(file) },
    framing: [
      {
        max_message_size: 65536,
        data_per_frame: per,
        block_length: blockSize,
        frames: Math.ceil((blockSize + DIGEST_BYTES) / per),
      },
      {
        max_message_size: 16384,
        data_per_frame: dataPerFrame(16384),
        block_length: 4 * 1024 * 1024,
        frames: Math.ceil((4 * 1024 * 1024 + DIGEST_BYTES) / dataPerFrame(16384)),
      },
    ],
    empty_file_sha256: sha(new Uint8Array(0)),
  };
}

describe('shared transfer vectors', () => {
  it('the engine reproduces shared/protocol/schemas/transfer-vectors.json', () => {
    const built = build();
    if (process.env.UPDATE_VECTORS === '1') writeFileSync(PATH, JSON.stringify(built, null, 2) + '\n');
    const committed = JSON.parse(readFileSync(PATH, 'utf8'));
    expect(built).toEqual(committed);
    const big = new Bitmap(5120);
    big.set(5119);
    expect(hex(big.bytes)).toBe(committed.bitmaps[3].hex);
  });
});
