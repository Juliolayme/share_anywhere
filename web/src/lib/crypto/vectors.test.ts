// @vitest-environment node
/**
 * Shared key-library vectors (shared/protocol/schemas/clipboard-vectors.json, docs/CLIPBOARD_PROTOCOL.md
 * §Keys). Android and iOS must reproduce every value. Both X25519 backends must produce the same file.
 * Regenerate with UPDATE_VECTORS=1 only when the format version changes.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { afterEach, describe, expect, it } from 'vitest';
import { deriveSubkey, deriveSubkeyBytes } from './adk';
import { RECOVERY_PARAMS, recoverySeed } from './argon';
import { b64uEncode, concatBytes, fromHex, hex, utf8 } from './encoding';
import { decryptItemText, encryptItemWithNonce, itemAad } from './item';
import { entropyToPhrase, normalizePhrase } from './phrase';
import { hkdfBytes } from './primitives';
import { WRAP_INFO, WRAP_PURPOSES, chainAad, unwrapAdk, unwrapChain, wrapAad, wrapAdk, wrapChain } from './wrap';
import { clampScalar, forceX25519Backend, x25519FromSecret, x25519SharedSecret } from './x25519';

const PATH = new URL('../../../../shared/protocol/schemas/clipboard-vectors.json', import.meta.url).pathname;
const seq = (n: number, from: number) => Uint8Array.from({ length: n }, (_, i) => (from + i) & 0xff);

const ADK_V1 = seq(32, 0x00);
const ADK_V2 = seq(32, 0x20);
const RECIPIENT_SECRET = seq(32, 0xc1);
const EPHEMERAL_SECRET = seq(32, 0xe3);
const WRAP_NONCE = seq(12, 0xb0);
const CHAIN_NONCE = seq(12, 0xc0);
const ITEM_NONCE = seq(12, 0xa0);
const RECOVERY_ENTROPY = fromHex('7f7f7f7f7f7f7f7f7f7f7f7f7f7f7f7f');
const RECOVERY_SALT = seq(16, 0x90);
const PLAINTEXT = 'Hello from Share Anywhere ✓ Xin chào';

async function build() {
  const subkeys = {
    clipboard: hex(await deriveSubkeyBytes(ADK_V1, 'clipboard')),
    history: hex(await deriveSubkeyBytes(ADK_V1, 'history')),
  };
  const items = [];
  for (const [purpose, id] of [
    ['history', '6f1e1b5a-3c1d-4a7e-9b2f-0c8d5e4a3b21'],
    ['clipboard', '2b7c9e40-1a5d-4f3b-8e6a-9d0c1f2e3a4b'],
  ] as const) {
    const key = await deriveSubkey(ADK_V1, purpose);
    const enc = await encryptItemWithNonce(key, id, 1, PLAINTEXT, ITEM_NONCE);
    expect(await decryptItemText(key, id, 1, enc)).toBe(PLAINTEXT);
    items.push({
      subkey: purpose,
      id,
      key_version: 1,
      nonce: hex(enc.nonce),
      plaintext_utf8: hex(utf8(PLAINTEXT)),
      aad_utf8: hex(itemAad(id, 1)),
      ciphertext: hex(enc.ciphertext),
      ciphertext_b64u: b64uEncode(enc.ciphertext),
    });
  }

  const recipient = await x25519FromSecret(RECIPIENT_SECRET);
  const ephemeral = await x25519FromSecret(EPHEMERAL_SECRET);
  const shared = await x25519SharedSecret(ephemeral.privateKey, recipient.publicKey);
  const salt = concatBytes(ephemeral.publicKey, recipient.publicKey);
  const wrapKey = await hkdfBytes(shared, salt, WRAP_INFO);
  const wraps = [];
  for (const purpose of WRAP_PURPOSES) {
    const blob = await wrapAdk(ADK_V2, recipient.publicKey, purpose, 2, { senderKey: ephemeral, nonce: WRAP_NONCE });
    expect(hex(await unwrapAdk(blob, recipient, purpose, 2))).toBe(hex(ADK_V2));
    wraps.push({
      purpose,
      key_version: 2,
      aad_utf8: hex(wrapAad(purpose, 2)),
      blob: hex(blob),
      blob_b64u: b64uEncode(blob),
    });
  }
  const chainBlob = await wrapChain(ADK_V2, ADK_V1, 2, { nonce: CHAIN_NONCE });
  expect(hex(await unwrapChain(chainBlob, ADK_V2, 2))).toBe(hex(ADK_V1));

  const phrase = entropyToPhrase(RECOVERY_ENTROPY);
  const typed = `  ${phrase.toUpperCase().split(' ').join('   ')}\t`;
  const seed = recoverySeed(typed, RECOVERY_SALT, RECOVERY_PARAMS);
  const recoveryPair = await x25519FromSecret(seed);

  return {
    $comment:
      'Generated by web/src/lib/crypto/vectors.test.ts (UPDATE_VECTORS=1). Format: docs/CLIPBOARD_PROTOCOL.md §Keys. Byte strings are lowercase hex unless the key ends in _b64u (base64url, no padding, the wire encoding). X25519 private keys are listed as given and after RFC 7748 clamping.',
    format_version: 1,
    adk: { key_version: 1, adk: hex(ADK_V1), hkdf: { hash: 'SHA-256', salt: '', length: 32 }, subkeys },
    items: { algorithm: 'AES-256-GCM, 16-byte tag appended', aad: '<id>|<key_version>', vectors: items },
    wrap: {
      algorithm: 'X25519 + HKDF-SHA256(salt = sender_pub || recipient_pub, info = "sa-wrap-v1") + AES-256-GCM',
      blob_layout: 'sender_pub(32) || nonce(12) || ciphertext+tag(48)',
      adk: hex(ADK_V2),
      recipient_private: hex(RECIPIENT_SECRET),
      recipient_private_clamped: hex(clampScalar(RECIPIENT_SECRET)),
      recipient_public: hex(recipient.publicKey),
      sender_private: hex(EPHEMERAL_SECRET),
      sender_private_clamped: hex(clampScalar(EPHEMERAL_SECRET)),
      sender_public: hex(ephemeral.publicKey),
      shared_secret: hex(shared),
      hkdf_salt: hex(salt),
      hkdf_info_utf8: hex(utf8(WRAP_INFO)),
      wrap_key: hex(wrapKey),
      nonce: hex(WRAP_NONCE),
      vectors: wraps,
    },
    chain: {
      algorithm: 'AES-256-GCM(key = ADK(v), plaintext = ADK(v-1), aad = "chain|<v>")',
      blob_layout: 'nonce(12) || ciphertext+tag(48)',
      key_version: 2,
      adk_v1: hex(ADK_V1),
      adk_v2: hex(ADK_V2),
      nonce: hex(CHAIN_NONCE),
      aad_utf8: hex(chainAad(2)),
      blob: hex(chainBlob),
    },
    recovery: {
      entropy: hex(RECOVERY_ENTROPY),
      phrase,
      typed_input: typed,
      normalized: normalizePhrase(typed),
      argon2id: { ...RECOVERY_PARAMS, version: 19, length: 32, salt: hex(RECOVERY_SALT) },
      password_utf8: hex(utf8(normalizePhrase(typed))),
      seed: hex(seed),
      private_clamped: hex(clampScalar(seed)),
      public_key: hex(recoveryPair.publicKey),
      public_key_b64u: b64uEncode(recoveryPair.publicKey),
    },
  };
}

afterEach(() => forceX25519Backend(null));

describe('clipboard-vectors.json', () => {
  it('the WebCrypto and @noble/curves backends both reproduce the shared vectors', { timeout: 60_000 }, async () => {
    forceX25519Backend('webcrypto');
    const native = await build();
    forceX25519Backend('noble');
    const fallback = await build();
    expect(fallback).toEqual(native);
    const text = `${JSON.stringify(native, null, 2)}\n`;
    if (process.env.UPDATE_VECTORS === '1') writeFileSync(PATH, text);
    expect(JSON.parse(readFileSync(PATH, 'utf8'))).toEqual(native);
  });
});
